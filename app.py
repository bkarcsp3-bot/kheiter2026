def _verify_password(stored_password, candidate_password):
    if not stored_password or not candidate_password:
        return False
    if stored_password.startswith(("scrypt:", "pbkdf2:")):
        return check_password_hash(stored_password, candidate_password)
    return stored_password == candidate_password


def _display_password(stored_password):
    if not stored_password:
        return "-"
    if stored_password.startswith(("scrypt:", "pbkdf2:")):
        return "مشفّرة (••••••••)"
    return stored_password


def ensure_turnout_schema(conn):
    conn.executescript("""
        CREATE TABLE IF NOT EXISTS office_turnout (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            center_id INTEGER NOT NULL,
            center_name TEXT NOT NULL,
            office_name TEXT NOT NULL,
            registered_voters INTEGER NOT NULL DEFAULT 0,
            voters_0930 INTEGER NOT NULL DEFAULT 0,
            voters_1400 INTEGER NOT NULL DEFAULT 0,
            voters_1700 INTEGER NOT NULL DEFAULT 0,
            voters_1900 INTEGER NOT NULL DEFAULT 0,
            filled_0930 INTEGER NOT NULL DEFAULT 0,
            filled_1400 INTEGER NOT NULL DEFAULT 0,
            filled_1700 INTEGER NOT NULL DEFAULT 0,
            filled_1900 INTEGER NOT NULL DEFAULT 0,
            updated_at TEXT DEFAULT '',
            UNIQUE(center_id, office_name),
            FOREIGN KEY (center_id) REFERENCES centers(center_id)
        );
    """)
    offices = conn.execute("""
        SELECT DISTINCT center_id, center_name, office_name
        FROM election_staff
        WHERE office_name != 'مركز التصويت'
        ORDER BY center_id, id
    """).fetchall()
    t_cols = [c["name"] for c in conn.execute("PRAGMA table_info(office_turnout)").fetchall()]
    for col_name in ("filled_0930", "filled_1400", "filled_1700", "filled_1900"):
        if col_name not in t_cols:
            conn.execute(f"ALTER TABLE office_turnout ADD COLUMN {col_name} INTEGER NOT NULL DEFAULT 0")
    for off in offices:
        conn.execute("""
            INSERT OR IGNORE INTO office_turnout (center_id, center_name, office_name)
            VALUES (?, ?, ?)
        """, (off["center_id"], off["center_name"], off["office_name"]))
    conn.execute("""
        CREATE TABLE IF NOT EXISTS user_passwords (
            username TEXT PRIMARY KEY,
            password TEXT NOT NULL,
            updated_at TEXT DEFAULT '',
            session_version TEXT NOT NULL DEFAULT 'v1'
        );
    """)
    up_cols = [c["name"] for c in conn.execute("PRAGMA table_info(user_passwords)").fetchall()]
    if "session_version" not in up_cols:
        conn.execute("ALTER TABLE user_passwords ADD COLUMN session_version TEXT NOT NULL DEFAULT 'v1'")
    for uname, uinfo in USERS.items():
        conn.execute("""
            INSERT OR IGNORE INTO user_passwords (username, password, updated_at, session_version)
            VALUES (?, ?, '', 'v1')
        """, (uname, uinfo["password"]))
    conn.commit()


def get_effective_users(conn=None):
    close_after = False
    if conn is None:
        conn = get_db()
        close_after = True
    ensure_turnout_schema(conn)
    db_rows = conn.execute("SELECT username, password, updated_at, session_version FROM user_passwords").fetchall()
    pw_map = {r["username"]: (r["password"], r["updated_at"], r["session_version"] or "v1") for r in db_rows}
    users_out = {}
    for uname, info in USERS.items():
        item = dict(info)
        if uname in pw_map and pw_map[uname][0]:
            item["password"] = pw_map[uname][0]
            item["password_display"] = _display_password(pw_map[uname][0])
            item["password_updated_at"] = pw_map[uname][1]
            item["session_version"] = pw_map[uname][2]
        else:
            item["password_display"] = _display_password(item["password"])
            item["password_updated_at"] = ""
            item["session_version"] = "v1"
        users_out[uname] = item
    if close_after:
        conn.close()
    return users_out


